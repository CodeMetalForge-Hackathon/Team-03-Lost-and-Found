"""Phase 0.3: index real night-sky photos.
- Wikimedia set: data/sky_photos/index.json (already geotagged/timestamped by the downloader) -> re-read EXIF too.
- AstroSmartphoneDataset: read EXIF with exifread, keep only files with DateTimeOriginal, note GPS.
Writes data/stars/astrosmartphone/index.json and data/PHOTO_INDEX.md."""
import json, pathlib, collections
import exifread

ROOT = pathlib.Path(__file__).resolve().parent
ASD = ROOT / "data" / "stars" / "astrosmartphone" / "extracted" / "AstroSmartphoneDataset"
WIKI = ROOT / "data" / "sky_photos"


def _ratio(v):
    try:
        return float(v.num) / float(v.den) if v.den else None
    except AttributeError:
        return float(v)


def gps_deg(tags, key, ref):
    if key not in tags:
        return None
    d, m, s = [_ratio(x) for x in tags[key].values]
    val = d + m / 60 + s / 3600
    if str(tags.get(ref, "")).strip() in ("S", "W"):
        val = -val
    return val


def read_exif(p):
    with open(p, "rb") as f:
        tags = exifread.process_file(f, details=False)
    out = {"datetime_original": str(tags["EXIF DateTimeOriginal"]) if "EXIF DateTimeOriginal" in tags else None,
           "offset_time": str(tags.get("EXIF OffsetTimeOriginal", "")) or None,
           "model": str(tags.get("Image Model", "")) or None,
           "focal_mm": _ratio(tags["EXIF FocalLength"].values[0]) if "EXIF FocalLength" in tags else None,
           "focal_35mm": int(str(tags["EXIF FocalLengthIn35mmFilm"])) if "EXIF FocalLengthIn35mmFilm" in tags else None,
           "exposure_s": _ratio(tags["EXIF ExposureTime"].values[0]) if "EXIF ExposureTime" in tags else None,
           "width": int(str(tags["EXIF ExifImageWidth"])) if "EXIF ExifImageWidth" in tags else None,
           "height": int(str(tags["EXIF ExifImageLength"])) if "EXIF ExifImageLength" in tags else None,
           "lat": gps_deg(tags, "GPS GPSLatitude", "GPS GPSLatitudeRef"),
           "lon": gps_deg(tags, "GPS GPSLongitude", "GPS GPSLongitudeRef")}
    return out


def main():
    rows, counts = [], collections.Counter()
    for p in sorted(ASD.rglob("*.jpg")):
        counts["asd_total"] += 1
        e = read_exif(p)
        if not e["datetime_original"]:
            counts["asd_no_time"] += 1
            continue
        e["file"] = str(p.relative_to(ROOT))
        e["subset"] = p.parent.name
        rows.append(e)
        counts["asd_with_time"] += 1
        counts["asd_with_gps"] += e["lat"] is not None
    (ROOT / "data/stars/astrosmartphone/index.json").write_text(json.dumps(rows, indent=0))
    by_sub = collections.Counter(r["subset"] for r in rows)
    gps_sub = collections.Counter(r["subset"] for r in rows if r["lat"] is not None)
    f35 = collections.Counter((r["subset"], r["focal_35mm"]) for r in rows)

    wiki = json.loads((WIKI / "index.json").read_text())
    wcount = collections.Counter()
    for w in wiki:
        e = read_exif(WIKI / w["file"]) if (WIKI / w["file"]).exists() else {}
        w["exif_focal_35mm"] = e.get("focal_35mm")
        w["exif_datetime"] = e.get("datetime_original")
        w["has_full_time"] = len(str(w.get("datetime_original", ""))) >= 16 or bool(e.get("datetime_original"))
        wcount["total"] += 1
        wcount["full_timestamp"] += w["has_full_time"]
        wcount["exif_focal"] += bool(e.get("focal_35mm"))
    (WIKI / "index_enriched.json").write_text(json.dumps(wiki, indent=1))

    md = ["# Real-photo index (generated by data_index.py)", "",
          "## AstroSmartphoneDataset (Google Pixel night-sight JPEGs)", "",
          f"- files: {counts['asd_total']}; with EXIF DateTimeOriginal (kept): {counts['asd_with_time']}; "
          f"without (dropped): {counts['asd_no_time']}; with EXIF GPS: {counts['asd_with_gps']}", "",
          "| subset | kept | with GPS |", "|---|---|---|"]
    md += [f"| {s} | {n} | {gps_sub.get(s, 0)} |" for s, n in sorted(by_sub.items())]
    md += ["", "35 mm-equivalent focal lengths (subset, f35: count): " +
           ", ".join(f"{s}/{f}:{n}" for (s, f), n in sorted(f35.items(), key=lambda x: str(x))), "",
           "## Wikimedia Commons geotagged night-sky photos (data/sky_photos)", "",
           f"- photos: {wcount['total']}; with date+time (not just a date): {wcount['full_timestamp']}; "
           f"with EXIF 35mm focal length: {wcount['exif_focal']}. All have lat/lon (geotag) and a CC licence (see index.json).", ""]
    (ROOT / "data/PHOTO_INDEX.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
