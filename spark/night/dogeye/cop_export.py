"""Export the run's swept-beam coverage as a dog run folder the orchestrator already consumes (night/data/dog/<name>/layers.json).

REAL: the range/IMU/sound stream of the run. SIMULATED: where it sits on the floor (placed at the start of the planned
dog course, i.e. the synthetic run's first track point, glass-wall leg pointing east). Alerts are carried for display with
confidence 0, so scenario.py never emits them into fusion (TILT = gait bob, BARK = loud sound, not a confirmed bark).

Usage: cop_export.py OUT_DIR NAME     e.g. cop_export.py out/run10 run10_dogeye
Undo:  rm -r ~/forge/night/data/dog/NAME
"""
from __future__ import annotations
import json, math, sys
from pathlib import Path
import numpy as np
from common import Run, Coverage, NO_ECHO_M

HERE = Path(__file__).resolve().parent
NIGHT = HERE.parent
OUT, NAME = Path(sys.argv[1]), sys.argv[2]
run = Run(OUT)
SYN = json.loads((NIGHT / "data/dog/run_00_synthetic/layers.json").read_text())
FB = SYN["floor_bounds"]; MK = SYN["markers"]
ox, oy = SYN["track"][0][1], SYN["track"][0][2]           # planned course start (floor m; +x east, +y south)


def to_floor(x, y):          # local frame (+y up) → floor frame (+y south), translated to the course start
    return ox + x, oy - y


CELL, NX, NY, X0, Y0 = 0.5, 14, 10, FB[0], FB[1]
TAU = 1.5
fine = Coverage(X0, X0 + NX * CELL, Y0, Y0 + NY * CELL, cell=0.05)
k = int(round(CELL / fine.cell))
snaps, track, hits = [], [], []
tq, dt = 0.0, 0.1
while tq <= run.T + 1.0 + 1e-9:
    x, y, h, d, i = run.pose(tq)
    fx, fy = to_floor(x, y); fh = -h                       # y flip mirrors the heading
    track.append([int(round(tq * 1000)), round(fx, 3), round(fy, 3)])
    j = min(i + 1, len(run.t) - 1)
    turning = run.hid[i] != run.hid[j] or (j > i and run.hdg[i] != run.hdg[j])
    if not turning:
        fine.add(fx, fy, fh, NO_ECHO_M if math.isnan(d) else d, dt)
        if not math.isnan(d) and abs(tq - round(tq)) < 1e-6:
            hits.append([int(round(tq * 1000)), round(fx + d * math.cos(fh), 3), round(fy + d * math.sin(fh), 3)])
    if abs(tq - round(tq)) < 1e-6:
        D = fine.dwell[:NY * k, :NX * k].reshape(NY, k, NX, k)
        frac = (D > 0).mean(axis=(1, 3))
        mean_dw = np.where(frac > 0, D.sum(axis=(1, 3)) / np.maximum((D > 0).sum(axis=(1, 3)), 1), 0)
        pod = frac * (1 - np.exp(-mean_dw / TAU))
        snaps.append({"t_ms": int(round(tq * 1000)), "pod": np.round(pod, 3).tolist()})
    tq = round(tq + dt, 2)

alerts = []
for a in run.alerts:
    x, y, *_ = run.pose(a["t"]); fx, fy = to_floor(x, y)
    alerts.append({"t_ms": int(a["t"] * 1000), "kind": f"dog_{a['kind'].lower()}", "source": "real:run10 board alert",
                   "x": round(fx, 3), "y": round(fy, 3), "confidence": 0.0,
                   "note": {"TILT": "gait bob while MOVING, not sitting", "BARK": "single loud sound at arrival (servos/handler likely)",
                            "STILL": "accelerometer quiet"}.get(a["kind"], "")})
L = {"run": NAME, "synthetic": False, "placement": "SIMULATED",
     "badge": f"REAL {run.meta['run'].split('_')[0]} range stream · SIMULATED placement",
     "dogeye": str(OUT.resolve().relative_to(HERE)),
     "t_start_ms": 0, "t_end_ms": int((run.T + 1) * 1000), "offset_ms": 0.0, "markers": MK, "floor_bounds": FB,
     "obstacles": [], "track": track,
     "coverage": {"cell_m": CELL, "nx": NX, "ny": NY, "x0": X0, "y0": Y0,
                  "model": "swept 15° sonar cone (no-echo credited 0.9 m); POD = covered-area fraction × (1 − exp(−dwell/1.5 s)) (illustrative)",
                  "snapshots": snaps},
     "alerts": alerts, "occupancy": {"hits": hits}, "video": None,
     "_note": "Generated by night/dogeye/cop_export.py. Range stream REAL (run10); placement on the floor SIMULATED; headings ROOM-PRIOR (not measured). Alerts carried with confidence 0 = display only, never sent to fusion."}
dst = NIGHT / "data/dog" / NAME
dst.mkdir(parents=True, exist_ok=True)
(dst / "layers.json").write_text(json.dumps(L))
pod = np.array(snaps[-1]["pod"])
print(f"{dst}/layers.json: {len(track)} track pts, {len(alerts)} alerts (confidence 0), {int((pod > 0.01).sum())} floor cells with POD>0.01, "
      f"max POD {pod.max():.2f}, cells POD≥0.5: {int((pod >= 0.5).sum())}")
